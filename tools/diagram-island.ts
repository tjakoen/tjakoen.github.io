// portfolio/tools/diagram-island.ts — scripts/diagram-island.js is GRAIN's diagram script (pan, zoom and
// hover tracing) as a file the note pages load. It is generated from GRAIN's own DIAGRAM_SCRIPT, never edited
// by hand, so the behavior has one home. A test fails when the file drifts.
//
//   bun tools/diagram-island.ts   # rewrite scripts/diagram-island.js
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DIAGRAM_SCRIPT } from "@tjakoen/grain/components/organisms/diagram/diagram.ts";

export const ISLAND_PATH = join(import.meta.dir, "..", "scripts", "diagram-island.js");
export const islandSource = () =>
  `// Generated by tools/diagram-island.ts from GRAIN's DIAGRAM_SCRIPT. Do not edit.\n` +
  DIAGRAM_SCRIPT.replace(/^<script>\s*/, "").replace(/\s*<\/script>$/, "") + "\n";

if (import.meta.main) { writeFileSync(ISLAND_PATH, islandSource()); console.log("wrote scripts/diagram-island.js"); }
